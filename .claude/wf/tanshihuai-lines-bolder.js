const DRAFT_SCHEMA = { type: 'object', properties: {
  file: { type: 'string' }, approach: { type: 'string' }, lines: { type: 'integer' }, self_check: { type: 'string' },
}, required: ['file', 'approach', 'lines', 'self_check'] }
const FINAL_SCHEMA = { type: 'object', properties: {
  out: { type: 'string' },
  recommended: { type: 'object', properties: { label: { type: 'string' }, reason: { type: 'string' }, mix: { type: 'array', items: { type: 'string' } } }, required: ['label', 'reason', 'mix'] },
  unresolved: { type: 'array', items: { type: 'string' } },
  rhythm: { type: 'string' }, summary: { type: 'string' },
}, required: ['out', 'recommended', 'unresolved', 'rhythm', 'summary'] }

log('主角台詞三組：起草')
const drafts = (await parallel(LENSES.map(l => () =>
  agent(draftPrompt(l), { label: `draft-${l.tag}:台詞`, phase: 'Draft', effort: 'xhigh', model: MODEL, schema: DRAFT_SCHEMA })
    .then(r => r ? { label: l.tag, ...r, file: draftPath(l.tag) } : null)))).filter(Boolean)
if (!drafts.length) return { date: DATE, error: 'all drafts failed' }
log(`${drafts.length} 組就位，送終審`)
const fin = await agent(finalPrompt(drafts), { label: 'final:台詞', phase: 'Final', effort: 'max', model: MODEL, schema: FINAL_SCHEMA })
if (!fin) return { date: DATE, error: 'final failed', drafts }
return { date: DATE, out: fin.out, recommended: fin.recommended, unresolved: fin.unresolved, rhythm: fin.rhythm, summary: fin.summary, drafts: drafts.map(d => ({ label: d.label, approach: d.approach, lines: d.lines })) }
